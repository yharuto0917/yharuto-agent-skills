import unittest

from src.services.order_service import create_order_summary, ping_service


class TestOrderService(unittest.TestCase):
    def test_ping_service(self) -> None:
        self.assertEqual(ping_service(), {"status": "ok"})

    def test_create_order_summary_valid(self) -> None:
        summary = create_order_summary(
            order_id="ord-101",
            items=[{"qty": 2, "unit_price_yen": 500}, {"qty": 1, "unit_price_yen": 300}],
            currency=" jpy ",
        )
        self.assertEqual(summary, {"order_id": "ord-101", "total": 1300, "currency": "JPY"})

    def test_create_order_summary_rejects_empty_items(self) -> None:
        with self.assertRaises(ValueError):
            create_order_summary(order_id="ord-102", items=[])

    def test_create_order_summary_rejects_invalid_currency(self) -> None:
        with self.assertRaises(ValueError):
            create_order_summary(
                order_id="ord-103",
                items=[{"qty": 1, "unit_price_yen": 100}],
                currency="US",
