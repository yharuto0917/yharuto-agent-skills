def _read_git_blob_text(
    repo_root: str,
    rev: str,
    path: str,
    max_bytes: int,
) -> Optional[str]:
    proc = _run_git_bytes(repo_root, ["show", f"{rev}:{path}"], check=False)
    if proc.returncode != 0:
        return None
    raw = proc.stdout[:max_bytes]
    if b"\x00" in raw[:8192]:
        return None
    return raw.decode("utf-8", errors="replace")


def _read_working_text(repo_root: str, path: str, max_bytes: int) -> Optional[str]:
    abs_path = os.path.join(repo_root, path)
    if not os.path.isfile(abs_path):
        return None
    try:
        with open(abs_path, "rb") as handle:
            raw = handle.read(max_bytes)
    except OSError:
        return None
    if b"\x00" in raw[:8192]:
        return None
    return raw.decode("utf-8", errors="replace")


def _read_after_text(
    repo_root: str,
    mode: str,
    head_sha: str,
    path: str,
    status: str,
    max_bytes: int,
) -> Optional[str]:
    if status == "D":
        return None
    if mode in ("working", "all"):
        return _read_working_text(repo_root, path, max_bytes)
    return _read_git_blob_text(repo_root, head_sha, path, max_bytes)


def _read_before_text(
    repo_root: str,
    before_rev: str,
    path: str,
    old_path: Optional[str],
    status: str,
    max_bytes: int,
) -> Optional[str]:
    if status in ("A", "?"):
        return None
    target = old_path or path
    return _read_git_blob_text(repo_root, before_rev, target, max_bytes)


def _get_file_patch(
    repo_root: str,
    mode: str,
    diff_base_rev: str,
    head_sha: str,
    path: str,
    old_path: Optional[str],
    status: str,
    max_patch_bytes: int,
) -> Optional[str]:
    """対象ファイル1件の diff パッチを取得する（サイズ超過時は None）。"""
    if status == "?":
        text = _read_working_text(repo_root, path, max_patch_bytes)
        if text is None:
            return None
        lines = text.splitlines()
        return f"@@ -0,0 +1,{len(lines)} @@\n" + "\n".join("+" + line for line in lines)

    args = ["diff", "--no-ext-diff", "-M"]
    if mode == "committed":
        args.extend([diff_base_rev, head_sha])
    else:
        args.append(diff_base_rev)
    args.append("--")
    if old_path and old_path != path:
        args.append(old_path)
    args.append(path)

    proc = _run_git_bytes(repo_root, args, check=False)
    if proc.returncode != 0 or len(proc.stdout) > max_patch_bytes:
        return None
    return proc.stdout.decode("utf-8", errors="replace")


def _iter_patch_changes(patch: str) -> Tuple[List[str], List[str]]:
    """パッチ本文から (追加行リスト, 削除行リスト) をハンク行数ベースで正確に返す。"""
    added_lines: List[str] = []
    deleted_lines: List[str] = []
    in_hunk = False
    old_rem = 0
    new_rem = 0
    has_counts = False

    for line in patch.splitlines():
        hm = HUNK_HEADER_RE.match(line)
        if hm and (not in_hunk or (has_counts and old_rem <= 0 and new_rem <= 0)):
            in_hunk = True
            old_rem = int(hm.group(2)) if hm.group(2) is not None else 1
            new_rem = int(hm.group(4)) if hm.group(4) is not None else 1
            has_counts = True
            continue
        if line.startswith("diff --git ") and (not in_hunk or (has_counts and old_rem <= 0 and new_rem <= 0)):
            in_hunk = False
            continue
        if not in_hunk:
            continue
        if has_counts and old_rem <= 0 and new_rem <= 0:
            in_hunk = False
            continue
        if line.startswith("\\"):
            continue
        if line.startswith("+"):
            if not has_counts and line.startswith("+++ "):
                continue
            added_lines.append(line[1:])
            new_rem -= 1
        elif line.startswith("-"):
            if not has_counts and line.startswith("--- "):
                continue
            deleted_lines.append(line[1:])
            old_rem -= 1
        elif line.startswith(" ") or line == "":
            old_rem -= 1
            new_rem -= 1
        else:
            in_hunk = False
    return added_lines, deleted_lines


def _is_import_path_only_patch(path: str, patch: str) -> bool:
    _, ext = posixpath.splitext(path.lower())
    if ext not in CODE_EXTENSIONS_FOR_IMPORT_ONLY:
        return False
    added_lines, deleted_lines = _iter_patch_changes(patch)
    changed = [ln.strip() for ln in added_lines + deleted_lines if ln.strip()]
    if not changed:
        return False
    return all(any(pat.match(ln) for pat in IMPORT_LINE_PATTERNS) for ln in changed)


