def _is_risk_path(path: str) -> bool:
    norm = posixpath.normpath(path)
    lower = norm.lower()
    base = posixpath.basename(lower)
    segs = [s.lower() for s in _split_segments(norm)[:-1]]
    if lower.endswith(".sql") or base == "schema.prisma" or base.endswith(".tf"):
        return True
    if base == "dockerfile" or base.startswith("dockerfile."):
        return True
    if ".github" in segs:
        idx = segs.index(".github")
        if idx + 1 < len(segs) and segs[idx + 1] == "workflows":
            return True
    if any(s in RISK_DIR_NAMES for s in segs):
        return True
    if base.startswith(("openapi.", "swagger.")) or ".openapi." in base or ".swagger." in base:
        return True
    tokens = _split_risk_tokens(norm)
    return bool(tokens & RISK_TOKENS)


