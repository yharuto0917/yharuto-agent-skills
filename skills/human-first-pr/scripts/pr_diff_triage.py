def _check_manual_gen_edit(
    *,
    path: str,
    status: str,
    before_text: Optional[str],
    after_text: Optional[str],
    had_header_override: Optional[bool] = None,
    has_header_override: Optional[bool] = None,
    patch: Optional[str],
    any_schema_changed: bool,
) -> Optional[str]:
    """自動生成ファイルへの手動改変疑いがあれば理由を返す。"""
    if status == "D":
        return None
    is_gen_path = _is_codegen_path(path)
    had_header = _has_gen_header(before_text) if had_header_override is None else had_header_override
    has_header = _has_gen_header(after_text) if has_header_override is None else has_header_override

    exempt_from_gen_scan = (
        _is_lockfile(path)
        or _is_snapshot(path)
        or _is_dependency_manifest(path)
        or _is_docs_file(path)
        or _is_test_file(path)
        or _is_orm_generated_metadata(path)
    )
    if exempt_from_gen_scan and not is_gen_path:
        return None

    if not (is_gen_path or had_header or has_header):
        return None

    reasons: List[str] = []
    if had_header and not has_header:
        reasons.append("元からあった自動生成ヘッダ (DO NOT EDIT 等) が削除された")
    if not any_schema_changed:
        reasons.append("同一 PR 内にスキーマ定義元の変更がない")
    if patch:
        added_lines, _ = _iter_patch_changes(patch)
        for line in added_lines:
            m = MANUAL_MARKER_RE.search(line)
            if m:
                reasons.append(f"追加行に手動編集マーカー ({m.group(0)}) を検出")
                break
    if not reasons:
        return None
    return " / ".join(reasons)


def _detect_boilerplate_heavy(
    *,
    path: str,
    status: str,
    reason: str,
    is_binary: bool,
    flags: Sequence[str],
    added_lines: Sequence[str],
) -> bool:
    """AI 由来の冗長な防衛チェック・空 catch/except・過剰コメントの比率が高いか判定する。"""
    if is_binary or status == "D":
        return False
    if "whitespace_or_format_only" in flags:
        return False
    if reason in (
        "lockfile",
        "snapshot",
        "orm_generated_metadata",
        "dependency_manifest",
        "build_artifact",
        "codegen",
        "documentation",
        "linter_or_ide_config",
        "stylesheet",
        "import_path_only",
        "pure_rename",
        "deleted_non_risk",
        "binary_asset",
    ):
        return False
    if _is_docs_file(path):
        return False

    non_empty = [ln.strip() for ln in added_lines if ln.strip()]
    total = len(non_empty)
    if total < 6:
        return False

    comment_count = 0
    defensive_count = 0
    empty_catch_count = 0
    empty_catch_lines = 0
    rethrow_catch_count = 0
    rethrow_lines = 0

    in_c_block_comment = False
    for idx, s in enumerate(non_empty):
        if in_c_block_comment:
            comment_count += 1
            if "*/" in s:
                in_c_block_comment = False
            continue
        if s.startswith("/*"):
            comment_count += 1
            if "*/" not in s[2:]:
                in_c_block_comment = True
            continue
        if BOILERPLATE_COMMENT_RE.match(s):
            comment_count += 1
            continue

        if DEFENSIVE_GUARD_RE.search(s):
            defensive_count += 1

        # Python except の空握りつぶし / 単純再送出
        em = EXCEPT_HEADER_RE.match(s)
        if em:
            rest = em.group(2).strip()
            if rest in ("pass", "...", "return", "return None") or rest.startswith(("pass #", "... #")):
                empty_catch_count += 1
                empty_catch_lines += 1
            elif idx + 1 < total:
                nxt = non_empty[idx + 1]
                if re.match(r"^(?:pass|\.\.\.|return(?:\s+None)?)\s*(?:#.*)?$", nxt):
                    empty_catch_count += 1
                    empty_catch_lines += 2
                elif re.match(r"^raise(?:\s+[A-Za-z_][A-Za-z0-9_]*)?\s*(?:#.*)?$", nxt) and (
                    idx + 2 >= total or not non_empty[idx + 2].startswith(("raise", "return"))
                ):
                    if " as " in em.group(1) and nxt.strip() != "raise":
                        alias = em.group(1).split(" as ", 1)[1].strip()
                        if nxt.strip() == f"raise {alias}":
                            rethrow_catch_count += 1
                            rethrow_lines += 2

        # JS/TS/Java/C# catch の空握りつぶし / 単純再送出
        cm = CATCH_HEADER_RE.search(s)
        if cm:
            tail = (cm.group(2) or "").strip()
            if tail == "}" or re.match(r"^(?://.*)?\}$", tail):
                empty_catch_count += 1
                empty_catch_lines += 1
            elif idx + 1 < total:
                nxt = non_empty[idx + 1]
                if nxt == "}" or (nxt.startswith("//") and idx + 2 < total and non_empty[idx + 2] == "}"):
                    empty_catch_count += 1
                    empty_catch_lines += 2
                elif re.match(r"^return(?:\s+(?:null|undefined))?;?$", nxt) and idx + 2 < total and non_empty[idx + 2] == "}":
                    empty_catch_count += 1
                    empty_catch_lines += 2
                elif cm.group(1):
                    var_name = cm.group(1).strip().split()[0].rstrip(":")
                    if re.match(rf"^throw\s+{re.escape(var_name)}\s*;?$", nxt):
                        rethrow_catch_count += 1
                        rethrow_lines += 2

    comment_ratio = comment_count / total
    if comment_count >= 3 and comment_ratio > 0.40:
        return True
    if empty_catch_count >= 2:
        return True

    combined_lines = comment_count + defensive_count + empty_catch_lines + rethrow_lines
    combined_ratio = combined_lines / total
    if empty_catch_count >= 1 and combined_ratio >= 0.25:
        return True
    if combined_ratio >= 0.50 and (defensive_count >= 3 or rethrow_catch_count >= 1):
        return True
    return False


def _strip_toml_comment(line: str) -> str:
    in_sq = False
    in_dq = False
    escaped = False
    for idx, ch in enumerate(line):
        if escaped:
            escaped = False
            continue
        if ch == "\\" and in_dq:
            escaped = True
            continue
        if ch == '"' and not in_sq:
            in_dq = not in_dq
        elif ch == "'" and not in_dq:
            in_sq = not in_sq
        elif ch == "#" and not in_sq and not in_dq:
            return line[:idx]
    return line


def _parse_toml_simple(text: str) -> Dict[str, Any]:
    """Python 3.9/3.10 向け pyproject.toml / Cargo.toml 簡易パーサ（tomllib フォールバック）。"""
    root: Dict[str, Any] = {}
    current = root
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = _strip_toml_comment(lines[i]).strip()
        i += 1
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            is_array_table = line.startswith("[[") and line.endswith("]]")
            header = line[2:-2].strip() if is_array_table else line[1:-1].strip()
            parts = [p.strip().strip('"').strip("'") for p in header.split(".") if p.strip()]
            target: Any = root
            for part in parts[:-1]:
                target = target.setdefault(part, {})
                if isinstance(target, list):
                    target = target[-1]
            last = parts[-1] if parts else ""
            if is_array_table:
                arr = target.setdefault(last, [])
                new_tbl: Dict[str, Any] = {}
                arr.append(new_tbl)
                current = new_tbl
            else:
                current = target.setdefault(last, {})
            continue
        if "=" not in line:
            continue
        key, val_raw = line.split("=", 1)
        key = key.strip().strip('"').strip("'")
        val_str = val_raw.strip()
        while (val_str.count("[") > val_str.count("]") or val_str.count("{") > val_str.count("}")) and i < len(lines):
            val_str += " " + _strip_toml_comment(lines[i]).strip()
            i += 1
        current[key] = _parse_toml_value(val_str)
    return root


def _parse_toml_value(val_str: str) -> Any:
    val_str = val_str.strip()
    if val_str.startswith("[") and val_str.endswith("]"):
        inner = val_str[1:-1].strip()
        if not inner:
            return []
        items = re.findall(r'"([^"]*)"|\'([^\']*)\'', inner)
        return [a or b for a, b in items]
    if val_str.startswith("{") and val_str.endswith("}"):
        inner = val_str[1:-1].strip()
        obj: Dict[str, Any] = {}
        for part in inner.split(","):
            if "=" in part:
                k, v = part.split("=", 1)
                obj[k.strip().strip('"').strip("'")] = _parse_toml_value(v)
        return obj
    if (val_str.startswith('"') and val_str.endswith('"')) or (val_str.startswith("'") and val_str.endswith("'")):
        return val_str[1:-1]
    return val_str


def _load_toml(text: str, use_tomllib: bool = True) -> Dict[str, Any]:
    if not text.strip():
        return {}
    if use_tomllib and tomllib is not None:
        try:
            data = tomllib.loads(text)
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return _parse_toml_simple(text)


def _parse_pep508_item(spec: str) -> Tuple[str, str]:
    clean = spec.split(";", 1)[0].strip()
    m = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?\s*(.*)$", clean)
    if not m:
        return clean, ""
    return m.group(1), m.group(2).strip()


def _extract_pyproject_deps(data: Dict[str, Any]) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    """pyproject.toml から (依存dict, 重要非依存キーdict, その他非依存キーdict) を抽出する。"""
    deps: Dict[str, str] = {}
    project = data.get("project") if isinstance(data.get("project"), dict) else {}
    for item in project.get("dependencies", []) if isinstance(project.get("dependencies"), list) else []:
        if isinstance(item, str):
            name, ver = _parse_pep508_item(item)
            if name:
                deps[name] = ver
    opt = project.get("optional-dependencies")
    if isinstance(opt, dict):
        for group_items in opt.values():
            if isinstance(group_items, list):
                for item in group_items:
                    if isinstance(item, str):
                        name, ver = _parse_pep508_item(item)
                        if name:
                            deps[name] = ver

    dep_groups = data.get("dependency-groups")
    if isinstance(dep_groups, dict):
        for group_items in dep_groups.values():
            if isinstance(group_items, list):
                for item in group_items:
                    if isinstance(item, str):
                        name, ver = _parse_pep508_item(item)
                        if name:
                            deps[name] = ver

    tool = data.get("tool") if isinstance(data.get("tool"), dict) else {}
    poetry = tool.get("poetry") if isinstance(tool.get("poetry"), dict) else {}
    for section_key in ("dependencies", "dev-dependencies"):
        sec = poetry.get(section_key)
        if isinstance(sec, dict):
            for pkg, val in sec.items():
                if pkg.lower() == "python":
                    continue
                ver = val.get("version", "") if isinstance(val, dict) else str(val)
                deps[pkg] = ver
    poetry_groups = poetry.get("group")
    if isinstance(poetry_groups, dict):
        for gval in poetry_groups.values():
            if isinstance(gval, dict) and isinstance(gval.get("dependencies"), dict):
                for pkg, val in gval["dependencies"].items():
                    ver = val.get("version", "") if isinstance(val, dict) else str(val)
                    deps[pkg] = ver

    critical_non_dep = {
        "build-system": data.get("build-system"),
        "project.scripts": project.get("scripts"),
        "project.gui-scripts": project.get("gui-scripts"),
        "project.entry-points": project.get("entry-points"),
        "tool.poetry.scripts": poetry.get("scripts"),
        "tool.poetry.plugins": poetry.get("plugins"),
    }
    other_project = {k: v for k, v in project.items() if k not in {"dependencies", "optional-dependencies", "scripts", "gui-scripts", "entry-points"}}
    other_tool = {k: v for k, v in tool.items() if k != "poetry"}
    other_non_dep = {
        "project_other": other_project,
        "tool_other": other_tool,
        "top_other": {k: v for k, v in data.items() if k not in {"project", "dependency-groups", "build-system", "tool"}},
    }
    return deps, critical_non_dep, other_non_dep


def _extract_json_deps(
    text: Optional[str],
    dep_keys: Sequence[str],
    critical_keys: Sequence[str],
) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    if not text or not text.strip():
        return {}, {}, {}
    try:
        data = json.loads(text)
    except ValueError:
        return {}, {}, {}
    if not isinstance(data, dict):
        return {}, {}, {}
    deps: Dict[str, str] = {}
    for dk in dep_keys:
        sec = data.get(dk)
        if isinstance(sec, dict):
            for pkg, ver in sec.items():
                if isinstance(pkg, str):
                    deps[pkg] = str(ver)
    crit = {k: data.get(k) for k in critical_keys if k in data}
    other = {k: data.get(k) for k in data if k not in set(dep_keys) and k not in set(critical_keys)}
    return deps, crit, other


def _extract_requirements_deps(text: Optional[str]) -> Dict[str, str]:
    deps: Dict[str, str] = {}
