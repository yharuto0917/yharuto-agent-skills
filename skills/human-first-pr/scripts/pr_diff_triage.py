def _run_git_bytes(
    repo_root: str,
    args: Sequence[str],
    *,
    check: bool = True,
) -> subprocess.CompletedProcess[bytes]:
    """core.quotePath=false と diff.relative=false を付けて Git を実行する。"""
    cmd = ["git", "-C", repo_root, "-c", "core.quotePath=false", "-c", "diff.relative=false", *args]
    try:
        proc = subprocess.run(cmd, capture_output=True, check=False)
    except OSError as exc:
        raise GitError(f"git の実行に失敗しました: {exc}") from exc
    if check and proc.returncode != 0:
        err = proc.stderr.decode("utf-8", errors="replace").strip()
        raise GitError(f"git {' '.join(args)} が失敗しました: {err or proc.returncode}")
    return proc


def _resolve_repo_root(repo_path: str) -> str:
    if not os.path.exists(repo_path):
        raise GitError(f"リポジトリパスが存在しません: {repo_path}")
    try:
        proc = subprocess.run(
            ["git", "-C", repo_path, "rev-parse", "--show-toplevel"],
            capture_output=True,
            check=False,
        )
    except OSError as exc:
        raise GitError(f"git の実行に失敗しました: {exc}") from exc
    if proc.returncode != 0:
        err = proc.stderr.decode("utf-8", errors="replace").strip()
        raise GitError(f"Git リポジトリではありません ({repo_path}): {err}")
    return proc.stdout.decode("utf-8", errors="surrogateescape").rstrip("\r\n")


def _try_resolve_repo_root(repo_path: Optional[str]) -> Optional[str]:
    if repo_path is None:
        return None
    if not os.path.isdir(repo_path):
        raise GitError(f"指定された --repo パスが存在しないかディレクトリではありません: {repo_path}")
    try:
        proc = subprocess.run(
            ["git", "-C", repo_path, "rev-parse", "--show-toplevel"],
            capture_output=True,
            check=False,
        )
    except OSError:
        return os.path.abspath(repo_path)
    if proc.returncode == 0:
        return proc.stdout.decode("utf-8", errors="surrogateescape").rstrip("\r\n")
    return os.path.abspath(repo_path)


def _verify_commit(repo_root: str, ref: str) -> Optional[str]:
    proc = _run_git_bytes(repo_root, ["rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"], check=False)
    if proc.returncode != 0:
        return None
    sha = proc.stdout.decode("utf-8", errors="replace").strip()
    return sha or None


def _current_branch(repo_root: str) -> str:
    proc = _run_git_bytes(repo_root, ["branch", "--show-current"], check=False)
    if proc.returncode != 0:
        return ""
    return proc.stdout.decode("utf-8", errors="replace").strip()


def _resolve_base_ref(
    repo_root: str,
    explicit_base: Optional[str],
    head_sha: str,
    mode: str,
) -> Tuple[str, Optional[str]]:
    """純ローカル Git のみでベースブランチを解決する（@{u} は使わない）。"""
    if explicit_base is not None:
        base_sha = _verify_commit(repo_root, explicit_base)
        if base_sha is None:
            raise GitError(f"指定された --base ref が見つかりません: {explicit_base}")
        return explicit_base, base_sha

    sym = _run_git_bytes(
        repo_root, ["symbolic-ref", "--quiet", "refs/remotes/origin/HEAD"], check=False
    )
    if sym.returncode == 0:
        ref_full = sym.stdout.decode("utf-8", errors="replace").strip()
        if ref_full.startswith("refs/remotes/"):
            cand = ref_full[len("refs/remotes/") :]
            cand_sha = _verify_commit(repo_root, cand)
            if cand_sha is not None:
                return cand, cand_sha

    current = _current_branch(repo_root)
    best: Optional[Tuple[int, int, str, str]] = None
    for idx, cand in enumerate(BASE_CANDIDATES):
        is_local = "/" not in cand
        if is_local and current and cand == current:
            continue
        cand_sha = _verify_commit(repo_root, cand)
        if cand_sha is None:
            continue
        mb_proc = _run_git_bytes(repo_root, ["merge-base", cand_sha, head_sha], check=False)
        if mb_proc.returncode != 0:
            continue
        mb_sha = mb_proc.stdout.decode("utf-8", errors="replace").strip()
        cnt_proc = _run_git_bytes(repo_root, ["rev-list", "--count", f"{mb_sha}..{head_sha}"], check=False)
        if cnt_proc.returncode != 0:
            continue
        try:
            distance = int(cnt_proc.stdout.decode("utf-8", errors="replace").strip())
        except ValueError:
            continue
        score = (distance, idx, cand, cand_sha)
        if best is None or score < best:
            best = score

    if best is not None:
        return best[2], best[3]

    if mode in ("working", "all"):
        return "HEAD", head_sha

    raise GitError(
        "ベースブランチを自動特定できませんでした（origin/HEAD や main/master/develop/trunk 候補が存在しません）。--base で明示指定してください。"
    )


def _decode_path(raw: bytes) -> str:
    return raw.decode("utf-8", errors="surrogateescape")


def _parse_numstat_z(data: bytes) -> Dict[str, Tuple[int, int, bool, Optional[str]]]:
    """`git diff --numstat -M -z` の出力を {path: (added, deleted, is_binary, old_path)} へ変換する。"""
    tokens = data.split(b"\x00")
    result: Dict[str, Tuple[int, int, bool, Optional[str]]] = {}
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if not tok:
            i += 1
            continue
        parts = tok.split(b"\t", 2)
        if len(parts) != 3:
            i += 1
            continue
        add_b, del_b, path_b = parts
        is_binary = add_b == b"-" and del_b == b"-"
        added = 0 if is_binary else int(add_b)
        deleted = 0 if is_binary else int(del_b)
        if path_b == b"":
            if i + 2 >= len(tokens):
                break
            old_path = _decode_path(tokens[i + 1])
            new_path = _decode_path(tokens[i + 2])
            result[new_path] = (added, deleted, is_binary, old_path)
            i += 3
        else:
            new_path = _decode_path(path_b)
            result[new_path] = (added, deleted, is_binary, None)
            i += 1
    return result


def _parse_name_status_z(data: bytes) -> List[Tuple[str, str, Optional[str]]]:
    """`git diff --name-status -M -z` の出力を [(status, path, old_path)] へ変換する。"""
    tokens = data.split(b"\x00")
    entries: List[Tuple[str, str, Optional[str]]] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if not tok:
            i += 1
            continue
        raw_status = tok.decode("ascii", errors="replace")
        code = raw_status[0]
        if code in ("R", "C"):
            if i + 2 >= len(tokens):
                break
            old_path = _decode_path(tokens[i + 1])
            new_path = _decode_path(tokens[i + 2])
            entries.append((code, new_path, old_path))
            i += 3
        else:
            if i + 1 >= len(tokens):
                break
            path = _decode_path(tokens[i + 1])
            entries.append((code, path, None))
            i += 2
    return entries


def _count_untracked_file(abs_path: str) -> Tuple[int, bool]:
    """未追跡ファイルを NUL バイト検査しつつストリーミングで行数を数える。"""
    if os.path.islink(abs_path):
        return 1, False
    try:
        size = os.path.getsize(abs_path)
    except OSError:
        return 0, False
    if size == 0:
        return 0, False
    lines = 0
    last_byte = b""
    is_binary = False
    try:
        with open(abs_path, "rb") as handle:
            first = handle.read(8192)
            if b"\x00" in first:
                return 0, True
            lines += first.count(b"\n")
            last_byte = first[-1:]
            while True:
                chunk = handle.read(65536)
                if not chunk:
                    break
                lines += chunk.count(b"\n")
                last_byte = chunk[-1:]
    except OSError:
        return 0, False
    if last_byte and last_byte != b"\n":
        lines += 1
    return lines, is_binary


def _split_segments(path: str) -> List[str]:
    return [p for p in posixpath.normpath(path).split("/") if p and p != "."]


def _split_risk_tokens(path: str) -> Set[str]:
    """CamelCase や記号区切りを分解してトークン集合を得る（author 等の誤爆防止）。"""
    parts = re.split(r"[/._\-]+", path)
    tokens: Set[str] = set()
    for part in parts:
        if not part:
            continue
        tokens.add(part.lower())
        camel_parts = re.findall(r"[A-Z]+(?=[A-Z][a-z]|\d|$)|[A-Z]?[a-z]+|\d+", part)
        for cp in camel_parts:
            tokens.add(cp.lower())
    return tokens


def _is_lockfile(path: str) -> bool:
    return posixpath.basename(path) in LOCKFILE_TO_MANIFESTS


def _is_snapshot(path: str) -> bool:
    base = posixpath.basename(path)
    if base.endswith(".snap") or base.endswith(".snap.new"):
        return True
    return "__snapshots__" in _split_segments(path)[:-1]


def _is_orm_generated_metadata(path: str) -> bool:
    norm = posixpath.normpath(path)
    segs = _split_segments(norm)
    for idx in range(len(segs) - 1):
        if segs[idx] == "drizzle" and segs[idx + 1] == "meta":
            return True
        if segs[idx] == "generated" and segs[idx + 1] == "prisma":
            return True
    if norm.endswith("prisma/migrations/migration_lock.toml"):
        return True
    return False


def _is_codegen_path(path: str) -> bool:
    base = posixpath.basename(path)
    segs = _split_segments(path)[:-1]
    if any(seg in CODEGEN_DIR_NAMES for seg in segs):
        return True
    if ".gen." in base or ".generated." in base:
        return True
    return base.endswith((".g.dart", ".freezed.dart", ".pb.go", "_pb2.py", "_pb2_grpc.py"))


def _is_build_artifact(path: str) -> bool:
    base = posixpath.basename(path)
    segs = _split_segments(path)[:-1]
    if any(seg in BUILD_ARTIFACT_DIR_NAMES for seg in segs):
        return True
    return base.endswith((".tsbuildinfo", ".min.js", ".min.css", ".bundle.js", ".map"))


def _is_dependency_manifest(path: str) -> bool:
    base = posixpath.basename(path)
    if base in MANIFEST_FILENAMES:
        return True
    if base.startswith("requirements") and base.endswith(".txt"):
        return True
    if base.startswith("build.gradle"):
        return True
    return False


def _is_test_file(path: str) -> bool:
    base = posixpath.basename(path)
    segs = [s.lower() for s in _split_segments(path)[:-1]]
    if any(s in TEST_DIR_NAMES for s in segs):
        return True
    stem, _ = posixpath.splitext(base)
    if base.startswith("test_") or stem.endswith("_test"):
        return True
    return bool(re.search(r"\.(?:test|spec)\.[^.]+$", base, re.IGNORECASE))


def _is_docs_file(path: str) -> bool:
    base = posixpath.basename(path).lower()
    if base.endswith((".md", ".mdx")):
        return True
    return "docs" in [s.lower() for s in _split_segments(path)[:-1]]


def _is_schema_source(path: str) -> bool:
    base = posixpath.basename(path).lower()
    if base.endswith((".proto", ".graphql", ".gql")):
        return True
    if base == "schema.prisma":
        return True
    if base.startswith(("openapi.", "swagger.", "codegen.", "drizzle.config.")):
        return True
