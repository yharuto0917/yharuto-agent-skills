def _run_git_bytes(
    repo_root: str,
    args: Sequence[str],
    *,
    check: bool = True,
) -> subprocess.CompletedProcess[bytes]:
    """core.quotePath=false と diff.relative=false を付けて Git を実行する。"""
    cmd = ["git", "-C", repo_root, "-c", "core.quotePath=false", "-c", "diff.relative=false", *args]
    try:
        proc = subprocess.run(cmd, capture_output=True, check=False)
    except OSError as exc:
        raise GitError(f"git の実行に失敗しました: {exc}") from exc
    if check and proc.returncode != 0:
        err = proc.stderr.decode("utf-8", errors="replace").strip()
        raise GitError(f"git {' '.join(args)} が失敗しました: {err or proc.returncode}")
    return proc


def _resolve_repo_root(repo_path: str) -> str:
    if not os.path.exists(repo_path):
        raise GitError(f"リポジトリパスが存在しません: {repo_path}")
    try:
        proc = subprocess.run(
            ["git", "-C", repo_path, "rev-parse", "--show-toplevel"],
            capture_output=True,
            check=False,
        )
    except OSError as exc:
        raise GitError(f"git の実行に失敗しました: {exc}") from exc
    if proc.returncode != 0:
        err = proc.stderr.decode("utf-8", errors="replace").strip()
        raise GitError(f"Git リポジトリではありません ({repo_path}): {err}")
    return proc.stdout.decode("utf-8", errors="surrogateescape").rstrip("\r\n")


def _verify_commit(repo_root: str, ref: str) -> Optional[str]:
    proc = _run_git_bytes(repo_root, ["rev-parse", "--verify", "--quiet", f"{ref}^{{commit}}"], check=False)
    if proc.returncode != 0:
        return None
    sha = proc.stdout.decode("utf-8", errors="replace").strip()
    return sha or None


def _current_branch(repo_root: str) -> str:
    proc = _run_git_bytes(repo_root, ["branch", "--show-current"], check=False)
    if proc.returncode != 0:
        return ""
    return proc.stdout.decode("utf-8", errors="replace").strip()


def _resolve_base_ref(
    repo_root: str,
    explicit_base: Optional[str],
    head_sha: str,
    mode: str,
) -> Tuple[str, Optional[str]]:
    """純ローカル Git のみでベースブランチを解決する（@{u} は使わない）。"""
    if explicit_base is not None:
        base_sha = _verify_commit(repo_root, explicit_base)
        if base_sha is None:
            raise GitError(f"指定された --base ref が見つかりません: {explicit_base}")
        return explicit_base, base_sha

    # 1. refs/remotes/origin/HEAD
    sym = _run_git_bytes(
        repo_root, ["symbolic-ref", "--quiet", "refs/remotes/origin/HEAD"], check=False
    )
    if sym.returncode == 0:
        ref_full = sym.stdout.decode("utf-8", errors="replace").strip()
        if ref_full.startswith("refs/remotes/"):
            cand = ref_full[len("refs/remotes/") :]
            cand_sha = _verify_commit(repo_root, cand)
            if cand_sha is not None:
                return cand, cand_sha

    # 2. 候補列から現在ブランチ同名ローカルを除外し、merge-base..head のコミット数最小を選択
    current = _current_branch(repo_root)
    best: Optional[Tuple[int, int, str, str]] = None
    for idx, cand in enumerate(BASE_CANDIDATES):
        is_local = "/" not in cand
        if is_local and current and cand == current:
            continue
        cand_sha = _verify_commit(repo_root, cand)
        if cand_sha is None:
            continue
        mb_proc = _run_git_bytes(repo_root, ["merge-base", cand_sha, head_sha], check=False)
        if mb_proc.returncode != 0:
            continue
        mb_sha = mb_proc.stdout.decode("utf-8", errors="replace").strip()
        cnt_proc = _run_git_bytes(repo_root, ["rev-list", "--count", f"{mb_sha}..{head_sha}"], check=False)
        if cnt_proc.returncode != 0:
            continue
        try:
            distance = int(cnt_proc.stdout.decode("utf-8", errors="replace").strip())
        except ValueError:
            continue
        score = (distance, idx, cand, cand_sha)
        if best is None or score < best:
            best = score

    if best is not None:
        return best[2], best[3]

    # デフォルトブランチ上等で他に候補がない場合の working/all フォールバック
    if mode in ("working", "all"):
        return "HEAD", head_sha

    raise GitError(
        "ベースブランチを自動特定できませんでした（origin/HEAD や main/master/develop/trunk 候補が存在しません）。--base で明示指定してください。"
    )


def _decode_path(raw: bytes) -> str:
    return raw.decode("utf-8", errors="surrogateescape")


def _parse_numstat_z(data: bytes) -> Dict[str, Tuple[int, int, bool, Optional[str]]]:
    """`git diff --numstat -M -z` の出力を {path: (added, deleted, is_binary, old_path)} へ変換する。"""
    tokens = data.split(b"\x00")
    result: Dict[str, Tuple[int, int, bool, Optional[str]]] = {}
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if not tok:
            i += 1
            continue
        parts = tok.split(b"\t", 2)
        if len(parts) != 3:
            i += 1
            continue
        add_b, del_b, path_b = parts
        is_binary = add_b == b"-" and del_b == b"-"
        added = 0 if is_binary else int(add_b)
        deleted = 0 if is_binary else int(del_b)
        if path_b == b"":
            if i + 2 >= len(tokens):
                break
            old_path = _decode_path(tokens[i + 1])
            new_path = _decode_path(tokens[i + 2])
            result[new_path] = (added, deleted, is_binary, old_path)
            i += 3
        else:
            new_path = _decode_path(path_b)
            result[new_path] = (added, deleted, is_binary, None)
            i += 1
    return result


def _parse_name_status_z(data: bytes) -> List[Tuple[str, str, Optional[str]]]:
    """`git diff --name-status -M -z` の出力を [(status, path, old_path)] へ変換する。"""
    tokens = data.split(b"\x00")
    entries: List[Tuple[str, str, Optional[str]]] = []
    i = 0
    while i < len(tokens):
        tok = tokens[i]
        if not tok:
            i += 1
            continue
        raw_status = tok.decode("ascii", errors="replace")
        code = raw_status[0]
        if code in ("R", "C"):
            if i + 2 >= len(tokens):
                break
            old_path = _decode_path(tokens[i + 1])
            new_path = _decode_path(tokens[i + 2])
            entries.append((code, new_path, old_path))
            i += 3
        else:
            if i + 1 >= len(tokens):
                break
            path = _decode_path(tokens[i + 1])
            entries.append((code, path, None))
            i += 2
    return entries


def _count_untracked_file(abs_path: str) -> Tuple[int, bool]:
    """未追跡ファイルを NUL バイト検査しつつストリーミングで行数を数える。"""
    if os.path.islink(abs_path):
        return 1, False
    try:
        size = os.path.getsize(abs_path)
    except OSError:
        return 0, False
    if size == 0:
        return 0, False
    lines = 0
    last_byte = b""
    is_binary = False
    try:
        with open(abs_path, "rb") as handle:
            first = handle.read(8192)
            if b"\x00" in first:
                return 0, True
            lines += first.count(b"\n")
            last_byte = first[-1:]
            while True:
                chunk = handle.read(65536)
                if not chunk:
                    break
                lines += chunk.count(b"\n")
                last_byte = chunk[-1:]
    except OSError:
        return 0, False
    if last_byte and last_byte != b"\n":
        lines += 1
    return lines, is_binary


def _split_segments(path: str) -> List[str]:
    return [p for p in posixpath.normpath(path).split("/") if p and p != "."]


def _split_risk_tokens(path: str) -> Set[str]:
    """CamelCase や記号区切りを分解してトークン集合を得る（author 等の誤爆防止）。"""
    parts = re.split(r"[/._\-]+", path)
    tokens: Set[str] = set()
    for part in parts:
        if not part:
            continue
        tokens.add(part.lower())
        camel_parts = re.findall(r"[A-Z]+(?=[A-Z][a-z]|\d|$)|[A-Z]?[a-z]+|\d+", part)
        for cp in camel_parts:
            tokens.add(cp.lower())
    return tokens


def _is_lockfile(path: str) -> bool:
    return posixpath.basename(path) in LOCKFILE_TO_MANIFESTS


def _is_snapshot(path: str) -> bool:
    base = posixpath.basename(path)
    if base.endswith(".snap") or base.endswith(".snap.new"):
        return True
    return "__snapshots__" in _split_segments(path)[:-1]


def _is_orm_generated_metadata(path: str) -> bool:
    norm = posixpath.normpath(path)
    segs = _split_segments(norm)
    for idx in range(len(segs) - 1):
        if segs[idx] == "drizzle" and segs[idx + 1] == "meta":
            return True
        if segs[idx] == "generated" and segs[idx + 1] == "prisma":
            return True
    if norm.endswith("prisma/migrations/migration_lock.toml"):
        return True
    return False


def _is_codegen_path(path: str) -> bool:
    base = posixpath.basename(path)
    segs = _split_segments(path)[:-1]
    if any(seg in CODEGEN_DIR_NAMES for seg in segs):
        return True
    if ".gen." in base or ".generated." in base:
        return True
    return base.endswith((".g.dart", ".freezed.dart", ".pb.go", "_pb2.py", "_pb2_grpc.py"))


def _is_build_artifact(path: str) -> bool:
    base = posixpath.basename(path)
    segs = _split_segments(path)[:-1]
    if any(seg in BUILD_ARTIFACT_DIR_NAMES for seg in segs):
        return True
    return base.endswith((".tsbuildinfo", ".min.js", ".min.css", ".bundle.js", ".map"))


def _is_dependency_manifest(path: str) -> bool:
    base = posixpath.basename(path)
    if base in MANIFEST_FILENAMES:
        return True
    if base.startswith("requirements") and base.endswith(".txt"):
        return True
    if base.startswith("build.gradle"):
        return True
    return False


def _is_test_file(path: str) -> bool:
    base = posixpath.basename(path)
    segs = [s.lower() for s in _split_segments(path)[:-1]]
    if any(s in TEST_DIR_NAMES for s in segs):
        return True
    stem, _ = posixpath.splitext(base)
    if base.startswith("test_") or stem.endswith("_test"):
        return True
    return bool(re.search(r"\.(?:test|spec)\.[^.]+$", base, re.IGNORECASE))


def _is_docs_file(path: str) -> bool:
    base = posixpath.basename(path).lower()
    if base.endswith((".md", ".mdx")):
        return True
    return "docs" in [s.lower() for s in _split_segments(path)[:-1]]


def _is_schema_source(path: str) -> bool:
    base = posixpath.basename(path).lower()
    if base.endswith((".proto", ".graphql", ".gql")):
        return True
    if base == "schema.prisma":
        return True
    if base.startswith(("openapi.", "swagger.", "codegen.", "drizzle.config.")):
        return True
    if ".openapi." in base or ".swagger." in base:
        return True
    return False


def _is_risk_path(path: str) -> bool:
    norm = posixpath.normpath(path)
    lower = norm.lower()
    base = posixpath.basename(lower)
    segs = [s.lower() for s in _split_segments(norm)[:-1]]
    if lower.endswith(".sql") or base == "schema.prisma" or base.endswith(".tf"):
        return True
    if base == "dockerfile" or base.startswith("dockerfile."):
        return True
    if ".github" in segs:
        idx = segs.index(".github")
        if idx + 1 < len(segs) and segs[idx + 1] == "workflows":
            return True
    if any(s in RISK_DIR_NAMES for s in segs):
        return True
    if base.startswith(("openapi.", "swagger.")) or ".openapi." in base or ".swagger." in base:
        return True
    tokens = _split_risk_tokens(norm)
    return bool(tokens & RISK_TOKENS)


def _is_linter_or_ide_config(path: str) -> bool:
    base = posixpath.basename(path)
    lower = base.lower()
    segs = [s.lower() for s in _split_segments(path)[:-1]]
    if any(s in {".vscode", ".idea"} for s in segs):
        return True
    if base in LINTER_IDE_FILES:
        return True
    if lower.startswith((".eslintrc", "eslint.config.", ".prettierrc", "prettier.config.", "tsconfig")):
        return True
    return False


def _is_stylesheet(path: str) -> bool:
    return posixpath.basename(path).lower().endswith((".css", ".scss", ".sass", ".less", ".styl"))


def _estimate_layer(path: str) -> str:
    norm = posixpath.normpath(path)
    lower = norm.lower()
    base = posixpath.basename(lower)
    segs = [s.lower() for s in _split_segments(norm)[:-1]]
    if _is_test_file(norm):
        return "tests"
    if _is_docs_file(norm) and not _is_risk_path(norm):
        return "docs"
    if (
        ".github" in segs
        or base == "dockerfile"
        or base.startswith("dockerfile.")
        or lower.endswith(".tf")
        or any(s in {"infra", "terraform", "k8s", "helm", "deploy"} for s in segs)
    ):
        return "infra_ci"
    if (
        lower.endswith(".sql")
        or base == "schema.prisma"
        or any(s in {"migrations", "prisma", "drizzle", "db", "repositories", "models"} for s in segs)
    ):
        return "data_db"
    if (
        any(s in {"routes", "controllers", "handlers", "endpoints", "api", "graphql", "grpc"} for s in segs)
        or "openapi" in base
        or "swagger" in base
        or lower.endswith(".proto")
    ):
        return "api"
    if (
        any(s in {"components", "pages", "views", "screens", "hooks", "styles"} for s in segs)
        or lower.endswith((".tsx", ".jsx", ".vue", ".svelte", ".css", ".scss", ".sass", ".less"))
    ):
        return "ui"
    if _is_linter_or_ide_config(norm) or _is_dependency_manifest(norm) or _is_lockfile(norm):
        return "config"
    return "domain_core"


def _read_git_blob_text(
    repo_root: str,
    rev: str,
    path: str,
    max_bytes: int,
) -> Optional[str]:
    proc = _run_git_bytes(repo_root, ["show", f"{rev}:{path}"], check=False)
    if proc.returncode != 0:
        return None
    raw = proc.stdout[:max_bytes]
    if b"\x00" in raw[:8192]:
        return None
    return raw.decode("utf-8", errors="replace")


def _read_working_text(repo_root: str, path: str, max_bytes: int) -> Optional[str]:
    abs_path = os.path.join(repo_root, path)
    if not os.path.isfile(abs_path):
        return None
    try:
        with open(abs_path, "rb") as handle:
            raw = handle.read(max_bytes)
    except OSError:
        return None
    if b"\x00" in raw[:8192]:
        return None
    return raw.decode("utf-8", errors="replace")


def _read_after_text(
    repo_root: str,
    mode: str,
    head_sha: str,
    path: str,
    status: str,
    max_bytes: int,
) -> Optional[str]:
    if status == "D":
        return None
    if mode in ("working", "all"):
        return _read_working_text(repo_root, path, max_bytes)
    return _read_git_blob_text(repo_root, head_sha, path, max_bytes)


def _read_before_text(
    repo_root: str,
    before_rev: str,
    path: str,
    old_path: Optional[str],
    status: str,
    max_bytes: int,
) -> Optional[str]:
    if status in ("A", "?"):
        return None
    target = old_path or path
    return _read_git_blob_text(repo_root, before_rev, target, max_bytes)


def _get_file_patch(
    repo_root: str,
    mode: str,
    diff_base_rev: str,
    head_sha: str,
    path: str,
    old_path: Optional[str],
    status: str,
    max_patch_bytes: int,
) -> Optional[str]:
    """対象ファイル1件の diff パッチを取得する（サイズ超過時は None）。"""
    if status == "?":
        text = _read_working_text(repo_root, path, max_patch_bytes)
        if text is None:
            return None
        return "\n".join("+" + line for line in text.splitlines())

    args = ["diff", "--no-ext-diff", "-M"]
    if mode == "committed":
        args.extend([diff_base_rev, head_sha])
    else:
        args.append(diff_base_rev)
    args.append("--")
    if old_path and old_path != path:
        args.append(old_path)
    args.append(path)

    proc = _run_git_bytes(repo_root, args, check=False)
    if proc.returncode != 0 or len(proc.stdout) > max_patch_bytes:
        return None
    return proc.stdout.decode("utf-8", errors="replace")


def _iter_patch_changes(patch: str) -> Tuple[List[str], List[str]]:
    """パッチ本文から (追加行リスト, 削除行リスト) をヘッダ除外で返す。"""
    added_lines: List[str] = []
    deleted_lines: List[str] = []
    in_hunk = False
    for line in patch.splitlines():
        if line.startswith("@@ "):
            in_hunk = True
            continue
        if line.startswith("diff --git "):
            in_hunk = False
            continue
        if not in_hunk:
            continue
        if line.startswith("+") and not line.startswith("+++ "):
            added_lines.append(line[1:])
        elif line.startswith("-") and not line.startswith("--- "):
            deleted_lines.append(line[1:])
    return added_lines, deleted_lines


def _is_import_path_only_patch(path: str, patch: str) -> bool:
    _, ext = posixpath.splitext(path.lower())
    if ext not in CODE_EXTENSIONS_FOR_IMPORT_ONLY:
        return False
    added_lines, deleted_lines = _iter_patch_changes(patch)
    changed = [ln.strip() for ln in added_lines + deleted_lines if ln.strip()]
    if not changed:
        return False
    return all(any(pat.match(ln) for pat in IMPORT_LINE_PATTERNS) for ln in changed)


def _has_gen_header(text: Optional[str]) -> bool:
    if not text:
        return False
    head_lines = "\n".join(text.splitlines()[:30])
    return bool(GEN_HEADER_RE.search(head_lines))


def _check_manual_gen_edit(
    *,
    path: str,
    status: str,
    before_text: Optional[str],
    after_text: Optional[str],
    patch: Optional[str],
    any_schema_changed: bool,
) -> Optional[str]:
    """自動生成ファイルへの手動改変疑いがあれば理由を返す。"""
    if status == "D":
        return None
    is_gen_path = _is_codegen_path(path)
    had_header = _has_gen_header(before_text)
    has_header = _has_gen_header(after_text)

    exempt_from_gen_scan = (
        _is_lockfile(path)
        or _is_snapshot(path)
        or _is_dependency_manifest(path)
        or _is_docs_file(path)
        or _is_test_file(path)
        or _is_orm_generated_metadata(path)
    )
    if exempt_from_gen_scan and not is_gen_path:
        # 例外: もし ORM メタデータや他のファイルで生成ヘッダ削除や明示的手動マーカーがあれば別途考慮するが
        # Cargo.lock / yarn.lock / poetry.lock などの生成ヘッダを codegen と誤認しないように除外する。
        return None

    if not (is_gen_path or had_header or has_header):
        return None

    reasons: List[str] = []
    if had_header and not has_header:
        reasons.append("元からあった自動生成ヘッダ (DO NOT EDIT 等) が削除された")
    if not any_schema_changed:
        reasons.append("同一 PR 内にスキーマ定義元の変更がない")
    if patch:
        added_lines, _ = _iter_patch_changes(patch)
        for line in added_lines:
            m = MANUAL_MARKER_RE.search(line)
            if m:
                reasons.append(f"追加行に手動編集マーカー ({m.group(0)}) を検出")
                break
    if not reasons:
        return None
    return " / ".join(reasons)


def _strip_toml_comment(line: str) -> str:
    in_sq = False
    in_dq = False
    escaped = False
    for idx, ch in enumerate(line):
        if escaped:
            escaped = False
            continue
        if ch == "\\" and in_dq:
            escaped = True
            continue
        if ch == '"' and not in_sq:
            in_dq = not in_dq
        elif ch == "'" and not in_dq:
            in_sq = not in_sq
        elif ch == "#" and not in_sq and not in_dq:
            return line[:idx]
    return line


def _parse_toml_simple(text: str) -> Dict[str, Any]:
    """Python 3.9/3.10 向け pyproject.toml / Cargo.toml 簡易パーサ（tomllib フォールバック）。"""
    root: Dict[str, Any] = {}
    current = root
    lines = text.splitlines()
    i = 0
    while i < len(lines):
        line = _strip_toml_comment(lines[i]).strip()
        i += 1
        if not line:
            continue
        if line.startswith("[") and line.endswith("]"):
            is_array_table = line.startswith("[[") and line.endswith("]]")
            header = line[2:-2].strip() if is_array_table else line[1:-1].strip()
            parts = [p.strip().strip('"').strip("'") for p in header.split(".") if p.strip()]
            target: Any = root
            for part in parts[:-1]:
                target = target.setdefault(part, {})
                if isinstance(target, list):
                    target = target[-1]
            last = parts[-1] if parts else ""
            if is_array_table:
                arr = target.setdefault(last, [])
                new_tbl: Dict[str, Any] = {}
                arr.append(new_tbl)
                current = new_tbl
            else:
                current = target.setdefault(last, {})
            continue
        if "=" not in line:
            continue
        key, val_raw = line.split("=", 1)
        key = key.strip().strip('"').strip("'")
        val_str = val_raw.strip()
        # 複数行配列・インラインテーブルの結合
        while (val_str.count("[") > val_str.count("]") or val_str.count("{") > val_str.count("}")) and i < len(lines):
            val_str += " " + _strip_toml_comment(lines[i]).strip()
            i += 1
        current[key] = _parse_toml_value(val_str)
    return root


def _parse_toml_value(val_str: str) -> Any:
    val_str = val_str.strip()
    if val_str.startswith("[") and val_str.endswith("]"):
        inner = val_str[1:-1].strip()
        if not inner:
            return []
        items = re.findall(r'"([^"]*)"|\'([^\']*)\'', inner)
        return [a or b for a, b in items]
    if val_str.startswith("{") and val_str.endswith("}"):
        inner = val_str[1:-1].strip()
        obj: Dict[str, Any] = {}
        for part in inner.split(","):
            if "=" in part:
                k, v = part.split("=", 1)
                obj[k.strip().strip('"').strip("'")] = _parse_toml_value(v)
        return obj
    if (val_str.startswith('"') and val_str.endswith('"')) or (val_str.startswith("'") and val_str.endswith("'")):
        return val_str[1:-1]
    return val_str


def _load_toml(text: str, use_tomllib: bool = True) -> Dict[str, Any]:
    if not text.strip():
        return {}
    if use_tomllib and tomllib is not None:
        try:
            data = tomllib.loads(text)
            if isinstance(data, dict):
                return data
        except Exception:
            pass
    return _parse_toml_simple(text)


def _parse_pep508_item(spec: str) -> Tuple[str, str]:
    clean = spec.split(";", 1)[0].strip()
    m = re.match(r"^([A-Za-z0-9][A-Za-z0-9._-]*)(?:\[[^\]]*\])?\s*(.*)$", clean)
    if not m:
        return clean, ""
    return m.group(1), m.group(2).strip()


def _extract_pyproject_deps(data: Dict[str, Any]) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    """pyproject.toml から (依存dict, 重要非依存キーdict, その他非依存キーdict) を抽出する。"""
    deps: Dict[str, str] = {}
    project = data.get("project") if isinstance(data.get("project"), dict) else {}
    for item in project.get("dependencies", []) if isinstance(project.get("dependencies"), list) else []:
        if isinstance(item, str):
            name, ver = _parse_pep508_item(item)
            if name:
                deps[name] = ver
    opt = project.get("optional-dependencies")
    if isinstance(opt, dict):
        for group_items in opt.values():
            if isinstance(group_items, list):
                for item in group_items:
                    if isinstance(item, str):
                        name, ver = _parse_pep508_item(item)
                        if name:
                            deps[name] = ver

    dep_groups = data.get("dependency-groups")
    if isinstance(dep_groups, dict):
        for group_items in dep_groups.values():
            if isinstance(group_items, list):
                for item in group_items:
                    if isinstance(item, str):
                        name, ver = _parse_pep508_item(item)
                        if name:
                            deps[name] = ver

    tool = data.get("tool") if isinstance(data.get("tool"), dict) else {}
    poetry = tool.get("poetry") if isinstance(tool.get("poetry"), dict) else {}
    for section_key in ("dependencies", "dev-dependencies"):
        sec = poetry.get(section_key)
        if isinstance(sec, dict):
            for pkg, val in sec.items():
                if pkg.lower() == "python":
                    continue
                ver = val.get("version", "") if isinstance(val, dict) else str(val)
                deps[pkg] = ver
    poetry_groups = poetry.get("group")
    if isinstance(poetry_groups, dict):
        for gval in poetry_groups.values():
            if isinstance(gval, dict) and isinstance(gval.get("dependencies"), dict):
                for pkg, val in gval["dependencies"].items():
                    ver = val.get("version", "") if isinstance(val, dict) else str(val)
                    deps[pkg] = ver

    critical_non_dep = {
        "build-system": data.get("build-system"),
        "project.scripts": project.get("scripts"),
        "project.gui-scripts": project.get("gui-scripts"),
        "project.entry-points": project.get("entry-points"),
        "tool.poetry.scripts": poetry.get("scripts"),
        "tool.poetry.plugins": poetry.get("plugins"),
    }
    other_project = {k: v for k, v in project.items() if k not in {"dependencies", "optional-dependencies", "scripts", "gui-scripts", "entry-points"}}
    other_tool = {k: v for k, v in tool.items() if k != "poetry"}
    other_non_dep = {
        "project_other": other_project,
        "tool_other": other_tool,
        "top_other": {k: v for k, v in data.items() if k not in {"project", "dependency-groups", "build-system", "tool"}},
    }
    return deps, critical_non_dep, other_non_dep


def _extract_json_deps(
    text: Optional[str],
    dep_keys: Sequence[str],
    critical_keys: Sequence[str],
) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    if not text or not text.strip():
        return {}, {}, {}
    try:
        data = json.loads(text)
    except ValueError:
        return {}, {}, {}
    if not isinstance(data, dict):
        return {}, {}, {}
    deps: Dict[str, str] = {}
    for dk in dep_keys:
        sec = data.get(dk)
        if isinstance(sec, dict):
            for pkg, ver in sec.items():
                if isinstance(pkg, str):
                    deps[pkg] = str(ver)
    crit = {k: data.get(k) for k in critical_keys if k in data}
    other = {k: data.get(k) for k in data if k not in set(dep_keys) and k not in set(critical_keys)}
    return deps, crit, other


def _extract_requirements_deps(text: Optional[str]) -> Dict[str, str]:
    deps: Dict[str, str] = {}
    if not text:
        return deps
    for raw_line in text.splitlines():
        line = raw_line.split("#", 1)[0].strip()
        if not line or line.startswith(("-", "--")):
            continue
        name, ver = _parse_pep508_item(line)
        if name:
            deps[name] = ver
    return deps


def _extract_cargo_deps(data: Dict[str, Any]) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    deps: Dict[str, str] = {}
    for key in ("dependencies", "dev-dependencies", "build-dependencies"):
        sec = data.get(key)
        if isinstance(sec, dict):
            for pkg, val in sec.items():
                ver = val.get("version", "") if isinstance(val, dict) else str(val)
                deps[pkg] = ver
    ws = data.get("workspace")
    if isinstance(ws, dict) and isinstance(ws.get("dependencies"), dict):
        for pkg, val in ws["dependencies"].items():
            ver = val.get("version", "") if isinstance(val, dict) else str(val)
            deps[pkg] = ver
    crit = {k: data.get(k) for k in ("bin", "lib", "features") if k in data}
    other = {k: v for k, v in data.items() if k not in {"dependencies", "dev-dependencies", "build-dependencies", "bin", "lib", "features"}}
    return deps, crit, other


def _extract_go_mod_deps(text: Optional[str]) -> Tuple[Dict[str, str], Dict[str, Any], Dict[str, Any]]:
    deps: Dict[str, str] = {}
    other_lines: List[str] = []
    if not text:
        return deps, {}, {}
    in_require = False
    for raw in text.splitlines():
        line = raw.split("//", 1)[0].strip()
        if not line:
            continue
        if line.startswith("require ("):
            in_require = True
            continue
        if in_require:
            if line == ")":
                in_require = False
                continue
            parts = line.split()
            if len(parts) >= 2:
                deps[parts[0]] = parts[1]
            continue
        if line.startswith("require "):
            parts = line[len("require ") :].split()
            if len(parts) >= 2:
                deps[parts[0]] = parts[1]
            continue
        other_lines.append(line)
    return deps, {}, {"directives": other_lines}


def _extract_generic_manifest_deps(base: str, text: Optional[str]) -> Dict[str, str]:
    deps: Dict[str, str] = {}
    if not text:
        return deps
    if base == "Gemfile":
        for m in re.finditer(r"""^\s*gem\s+['"]([^'"]+)['"](?:\s*,\s*['"]([^'"]+)['"])?""", text, re.MULTILINE):
            deps[m.group(1)] = m.group(2) or ""
    elif base == "pom.xml":
        for m in re.finditer(
            r"<dependency>\s*.*?<artifactId>([^<]+)</artifactId>(?:\s*.*?<version>([^<]+)</version>)?.*?</dependency>",
            text,
            re.DOTALL,
        ):
            deps[m.group(1).strip()] = (m.group(2) or "").strip()
    elif base.startswith("build.gradle"):
        for m in re.finditer(
            r"""(?:implementation|api|compileOnly|runtimeOnly|testImplementation)\s*\(?\s*['"]([^:'"]+:[^:'"]+)(?::([^'"]+))?['"]""",
            text,
        ):
            deps[m.group(1)] = m.group(2) or ""
    return deps


def _diff_dep_maps(
    before_deps: Dict[str, str],
    after_deps: Dict[str, str],
) -> Tuple[List[Dict[str, str]], List[Dict[str, str]], List[Dict[str, str]]]:
    added = [{"name": k, "version": after_deps[k]} for k in sorted(after_deps) if k not in before_deps]
    updated = [
        {"name": k, "from_version": before_deps[k], "to_version": after_deps[k]}
        for k in sorted(after_deps)
        if k in before_deps and before_deps[k] != after_deps[k]
    ]
    removed = [{"name": k, "version": before_deps[k]} for k in sorted(before_deps) if k not in after_deps]
    return added, updated, removed


def _analyze_manifest(
    path: str,
    before_text: Optional[str],
    after_text: Optional[str],
) -> Tuple[Dict[str, Any], str]:
    """マニフェストの変更を解析し (dependencyオブジェクト, 昇格レベル 'none'|'skim'|'must_read') を返す。"""
    base = posixpath.basename(path)
    before_crit: Dict[str, Any] = {}
    after_crit: Dict[str, Any] = {}
    before_other: Dict[str, Any] = {}
    after_other: Dict[str, Any] = {}

    if base == "package.json":
        dep_keys = (
            "dependencies",
            "devDependencies",
            "peerDependencies",
            "optionalDependencies",
            "bundledDependencies",
            "bundleDependencies",
            "overrides",
            "resolutions",
        )
        crit_keys = ("scripts", "exports", "bin", "imports", "workspaces")
        before_deps, before_crit, before_other = _extract_json_deps(before_text, dep_keys, crit_keys)
        after_deps, after_crit, after_other = _extract_json_deps(after_text, dep_keys, crit_keys)
    elif base == "composer.json":
        dep_keys = ("require", "require-dev")
        crit_keys = ("scripts", "bin", "autoload", "autoload-dev")
        before_deps, before_crit, before_other = _extract_json_deps(before_text, dep_keys, crit_keys)
        after_deps, after_crit, after_other = _extract_json_deps(after_text, dep_keys, crit_keys)
    elif base == "pyproject.toml":
        before_deps, before_crit, before_other = _extract_pyproject_deps(_load_toml(before_text or ""))
        after_deps, after_crit, after_other = _extract_pyproject_deps(_load_toml(after_text or ""))
    elif base == "Cargo.toml":
        before_deps, before_crit, before_other = _extract_cargo_deps(_load_toml(before_text or ""))
        after_deps, after_crit, after_other = _extract_cargo_deps(_load_toml(after_text or ""))
    elif base == "go.mod":
        before_deps, before_crit, before_other = _extract_go_mod_deps(before_text)
        after_deps, after_crit, after_other = _extract_go_mod_deps(after_text)
    elif base.startswith("requirements") and base.endswith(".txt"):
        before_deps = _extract_requirements_deps(before_text)
        after_deps = _extract_requirements_deps(after_text)
    else:
        before_deps = _extract_generic_manifest_deps(base, before_text)
        after_deps = _extract_generic_manifest_deps(base, after_text)

    added, updated, removed = _diff_dep_maps(before_deps, after_deps)
    crit_changed = before_crit != after_crit
    other_changed = before_other != after_other
    non_dep_changed = crit_changed or other_changed
    promotion = "must_read" if crit_changed else ("skim" if other_changed else "none")
    dep_obj = {
        "manifest": path,
        "added": added,
        "updated": updated,
        "removed": removed,
        "non_dependency_changes": non_dep_changed,
    }
    return dep_obj, promotion


def _detect_test_skip_or_assertion_removal(patch: Optional[str]) -> bool:
    if not patch:
        return False
    added_lines, deleted_lines = _iter_patch_changes(patch)
    if any(TEST_SKIP_RE.search(ln) for ln in added_lines):
        return True
    removed_asserts = any(ASSERTION_RE.search(ln) for ln in deleted_lines)
    added_asserts = any(ASSERTION_RE.search(ln) for ln in added_lines)
    if removed_asserts and not added_asserts:
        return True
    return False


def _determine_provisional_size(
    *,
    effective_files: int,
    effective_lines: int,
    code_layers: List[str],
    special_case: Optional[str],
    has_manual_gen_edit: bool,
    has_risk_path: bool,
    est_max_minutes: int,
) -> Tuple[str, List[str]]:
    reasons: List[str] = []

    if special_case == "empty_diff":
        return "S", ["empty_diff (変更ファイル 0件)"]

    if special_case == "skip_only" and not has_manual_gen_edit:
        return "S", ["skip_only (実質コード 0行 / lockfile・自動生成のみ)"]

    if (
        special_case == "docs_or_config_only"
        and effective_files <= 2
        and effective_lines < 50
        and not has_manual_gen_edit
        and not has_risk_path
    ):
        return "S", [
            f"docs_or_config_only (effective_files={effective_files} <= 2, effective_lines={effective_lines} < 50)"
        ]

    if (
        effective_files <= 2
        and effective_lines < 30
        and len(code_layers) <= 1
        and not has_manual_gen_edit
        and not has_risk_path
    ):
        return "S", [
            f"effective_files={effective_files} (<=2)",
            f"effective_lines={effective_lines} (<30)",
            f"code_layers={len(code_layers)} (<=1)",
        ]

    if special_case == "docs_or_config_only" or (effective_files <= 10 and effective_lines <= 300):
        if special_case == "docs_or_config_only":
            reasons.append("docs_or_config_only (>=3 files or >=50 lines)")
        else:
            reasons.append(f"effective_files={effective_files} (<=10)")
            reasons.append(f"effective_lines={effective_lines} (<=300)")
            if has_risk_path and effective_files <= 2 and effective_lines < 30:
                reasons.append("risk_path touched (SからMへ昇格)")
            if has_manual_gen_edit and effective_files <= 2 and effective_lines < 30:
                reasons.append("SUSPECTED_MANUAL_GEN_EDIT (SからMへ昇格)")
        return "M", reasons

    if special_case != "deletion_heavy":
        xl_reasons: List[str] = []
        if effective_lines > 600:
            xl_reasons.append(f"effective_lines={effective_lines} (>600)")
        if effective_files > 20:
            xl_reasons.append(f"effective_files={effective_files} (>20)")
        if est_max_minutes > 45:
            xl_reasons.append(f"estimated_review_minutes.max={est_max_minutes} (>45)")
        if len(code_layers) >= 4 and effective_lines > 400:
            xl_reasons.append(f"code_layers={len(code_layers)} (>=4) and effective_lines={effective_lines} (>400)")
        if xl_reasons:
            return "XL", xl_reasons

    if special_case == "deletion_heavy":
        reasons.append("deletion_heavy (削除主体PRのためXL分割強制を除外)")
    else:
        reasons.append(f"effective_files={effective_files} (<=20)")
        reasons.append(f"effective_lines={effective_lines} (<=600)")
    return "L", reasons


def analyze_repo(
    *,
    repo_path: str,
    base: Optional[str],
    head: str,
    mode: str,
    max_patch_bytes: int,
) -> Dict[str, Any]:
    """リポジトリ差分を解析し、トリアージ結果辞書を返す。"""
    repo_root = _resolve_repo_root(repo_path)
    head_sha = _verify_commit(repo_root, head)
    if head_sha is None:
        raise GitError(f"指定された --head ref が見つかりません（またはコミット未作成）: {head}")

    base_ref, base_sha = _resolve_base_ref(repo_root, base, head_sha, mode)
    assert base_sha is not None

    warnings: List[Dict[str, str]] = []
    if mode == "working":
        merge_base_sha = head_sha
        diff_target_args = [head_sha]
    else:
        mb_proc = _run_git_bytes(repo_root, ["merge-base", base_sha, head_sha], check=False)
        if mb_proc.returncode == 0:
            merge_base_sha = mb_proc.stdout.decode("utf-8", errors="replace").strip()
        else:
            merge_base_sha = base_sha
            warnings.append({
                "code": "SHALLOW_OR_UNRELATED_HISTORY",
                "severity": "warn",
                "path": "",
                "message": "git merge-base を解決できないため 2点ドット差分で代替しました（shallow clone の可能性があります）。",
            })
        if mode == "committed":
            diff_target_args = [merge_base_sha, head_sha]
        else:  # all
            diff_target_args = [merge_base_sha]

    numstat_raw = _run_git_bytes(repo_root, ["diff", "--numstat", "-M", "-z", *diff_target_args]).stdout
    status_raw = _run_git_bytes(repo_root, ["diff", "--name-status", "-M", "-z", *diff_target_args]).stdout
    w_numstat_raw = _run_git_bytes(repo_root, ["diff", "-w", "--numstat", "-M", "-z", *diff_target_args]).stdout

    numstat_map = _parse_numstat_z(numstat_raw)
    w_numstat_map = _parse_numstat_z(w_numstat_raw)
    status_entries = _parse_name_status_z(status_raw)

    raw_items: List[Dict[str, Any]] = []
    seen_paths: Set[str] = set()
    for status, path, old_path in status_entries:
        seen_paths.add(path)
        added, deleted, is_binary, ns_old = numstat_map.get(path, (0, 0, False, old_path))
        eff_old = old_path or ns_old
        w_added, w_deleted, _, _ = w_numstat_map.get(path, (0, 0, is_binary, eff_old))
        flags: List[str] = []
        if not is_binary and (added > 0 or deleted > 0) and w_added == 0 and w_deleted == 0:
            flags.append("whitespace_or_format_only")
        raw_items.append({
            "path": path,
            "old_path": eff_old,
            "status": status,
            "added": added,
            "deleted": deleted,
            "is_binary": is_binary,
            "flags": flags,
        })

    if mode in ("working", "all"):
        untracked_raw = _run_git_bytes(repo_root, ["ls-files", "--others", "--exclude-standard", "-z"]).stdout
        for raw_p in untracked_raw.split(b"\x00"):
            if not raw_p:
                continue
            path = _decode_path(raw_p)
            if path in seen_paths:
                continue
            seen_paths.add(path)
            lines, is_binary = _count_untracked_file(os.path.join(repo_root, path))
            raw_items.append({
                "path": path,
                "old_path": None,
                "status": "?",
                "added": lines,
                "deleted": 0,
                "is_binary": is_binary,
                "flags": ["untracked"],
            })

    changed_basenames = {posixpath.basename(it["path"]) for it in raw_items}
    any_schema_changed = any(_is_schema_source(it["path"]) for it in raw_items)

    must_read: List[Dict[str, Any]] = []
    skim: List[Dict[str, Any]] = []
    safe_to_skip: List[Dict[str, Any]] = []
    dependencies: List[Dict[str, Any]] = []

    for item in raw_items:
        path = item["path"]
        old_path = item["old_path"]
        status = item["status"]
        added = item["added"]
        deleted = item["deleted"]
        is_binary = item["is_binary"]
        flags = list(item["flags"])
        layer = _estimate_layer(path)
        risk_path = _is_risk_path(path)

        category = "must_read"
        reason = "production_code"
        patch_cache: Optional[str] = None
        patch_loaded = False

        def load_patch() -> Optional[str]:
            nonlocal patch_cache, patch_loaded
            if not patch_loaded:
                patch_loaded = True
                if not is_binary:
                    patch_cache = _get_file_patch(
                        repo_root, mode, merge_base_sha, head_sha, path, old_path, status, max_patch_bytes
                    )
            return patch_cache

        if _is_lockfile(path):
            category = "safe_to_skip"
            reason = "lockfile"
            expected_manifests = LOCKFILE_TO_MANIFESTS.get(posixpath.basename(path), ())
            if expected_manifests and not (changed_basenames & set(expected_manifests)):
                warnings.append({
                    "code": "LOCKFILE_WITHOUT_MANIFEST",
                    "severity": "warn",
                    "path": path,
                    "message": f"対応するマニフェスト ({', '.join(expected_manifests)}) に変更がないまま lockfile が変更されています。",
                })
        elif _is_snapshot(path):
            category = "safe_to_skip"
            reason = "snapshot"
        elif _is_orm_generated_metadata(path):
            category = "safe_to_skip"
            reason = "orm_generated_metadata"
        elif _is_dependency_manifest(path):
            category = "safe_to_skip"
            reason = "dependency_manifest"
            before_t = _read_before_text(repo_root, merge_base_sha, path, old_path, status, max_patch_bytes)
            after_t = _read_after_text(repo_root, mode, head_sha, path, status, max_patch_bytes)
            dep_obj, promo = _analyze_manifest(path, before_t, after_t)
            dependencies.append(dep_obj)
            if promo == "must_read":
                category = "must_read"
                reason = "manifest_non_dependency_critical"
                flags.append("non_dependency_manifest_change")
                warnings.append({
                    "code": "NON_DEPENDENCY_MANIFEST_CHANGE",
                    "severity": "warn",
                    "path": path,
                    "message": "マニフェストの scripts / exports / bin 等（非依存キー）が変更されたため must_read へ昇格しました。",
                })
            elif promo == "skim":
                category = "skim"
                reason = "manifest_non_dependency_other"
                flags.append("non_dependency_manifest_change")
                warnings.append({
                    "code": "NON_DEPENDENCY_MANIFEST_CHANGE",
                    "severity": "warn",
                    "path": path,
                    "message": "マニフェストの依存以外の設定キーが変更されたため skim へ昇格しました。",
                })
        elif _is_build_artifact(path):
            category = "safe_to_skip"
            reason = "build_artifact"
        elif _is_codegen_path(path):
            category = "safe_to_skip"
            reason = "codegen"
        elif _is_test_file(path):
            category = "skim"
            reason = "test_file"
            if status != "D" and _detect_test_skip_or_assertion_removal(load_patch()):
                category = "must_read"
                reason = "test_skip_or_assertion_removal"
                flags.append("test_skip_or_assertion_removal")
                warnings.append({
                    "code": "TEST_SKIP_OR_ASSERTION_REMOVAL",
                    "severity": "warn",
                    "path": path,
                    "message": "テストの skip 追加またはアサーション削除のみが検出されたため must_read へ昇格しました。",
                })
        elif status == "R" and added == 0 and deleted == 0:
            category = "skim"
            reason = "pure_rename"
        elif risk_path:
            if status == "D":
                category = "must_read"
                reason = "risk_path_deletion"
            else:
                category = "must_read"
                reason = "risk_path"
        elif _is_docs_file(path):
            category = "skim"
            reason = "documentation"
        elif _is_linter_or_ide_config(path):
            category = "skim"
            reason = "linter_or_ide_config"
        elif _is_stylesheet(path):
            category = "skim"
            reason = "stylesheet"
        elif status == "D":
            category = "skim"
            reason = "deleted_non_risk"
        elif is_binary:
            category = "skim"
            reason = "binary_asset"
        else:
            category = "must_read"
            reason = "production_code"

        # import パス置換のみ判定 (リスクパス以外、または生成物でない通常修正コード)
        if (
            category in ("must_read", "skim")
            and status == "M"
            and not is_binary
            and reason not in ("test_skip_or_assertion_removal", "manifest_non_dependency_critical")
        ):
            patch_txt = load_patch()
            if patch_txt and _is_import_path_only_patch(path, patch_txt):
                category = "safe_to_skip"
                reason = "import_path_only"
                flags.append("import_path_only")

        # 自動生成ファイル手動改変チェック（対象となりうるコード・生成パスを検査）
        if reason not in ("lockfile", "snapshot", "orm_generated_metadata", "dependency_manifest", "documentation", "test_file", "test_skip_or_assertion_removal"):
            before_t = _read_before_text(repo_root, merge_base_sha, path, old_path, status, min(max_patch_bytes, 16384))
            after_t = _read_after_text(repo_root, mode, head_sha, path, status, min(max_patch_bytes, 16384))
            manual_reason = _check_manual_gen_edit(
                path=path,
                status=status,
                before_text=before_t,
                after_text=after_t,
                patch=load_patch() if (_is_codegen_path(path) or _has_gen_header(before_t) or _has_gen_header(after_t)) else None,
                any_schema_changed=any_schema_changed,
            )
            if manual_reason:
                category = "must_read"
                reason = "suspected_manual_gen_edit"
                flags.append("suspected_manual_gen_edit")
                warnings.append({
                    "code": "SUSPECTED_MANUAL_GEN_EDIT",
                    "severity": "error",
                    "path": path,
                    "message": f"自動生成ファイルへの手動改変の疑い ({manual_reason}) のため must_read へ強制昇格しました。",
                })

        entry: Dict[str, Any] = {
            "path": path,
            "status": status,
            "added": added,
            "deleted": deleted,
            "is_binary": is_binary,
            "layer": layer,
            "reason": reason,
            "is_risk_path": risk_path,
            "flags": flags,
        }
        if old_path:
            entry["old_path"] = old_path

        if category == "must_read":
            must_read.append(entry)
        elif category == "skim":
            skim.append(entry)
        else:
            safe_to_skip.append(entry)

    # 集計
    total_files = len(raw_items)
    total_added = sum(it["added"] for it in raw_items)
    total_deleted = sum(it["deleted"] for it in raw_items)
    total_lines = total_added + total_deleted

    must_read_files = len(must_read)
    must_read_lines = sum(f["added"] + f["deleted"] for f in must_read)
    skim_files = len(skim)
    skim_lines = sum(f["added"] + f["deleted"] for f in skim)
    safe_to_skip_files = len(safe_to_skip)
    safe_to_skip_lines = sum(f["added"] + f["deleted"] for f in safe_to_skip)

    effective_list = must_read + skim
    effective_files = len(effective_list)
    effective_added = sum(f["added"] for f in effective_list)
    effective_deleted = sum(f["deleted"] for f in effective_list)
    effective_lines = effective_added + effective_deleted

    if total_lines > 0:
        noise_ratio_pct = round((safe_to_skip_lines / total_lines) * 100.0, 1)
    elif total_files > 0:
        noise_ratio_pct = round((safe_to_skip_files / total_files) * 100.0, 1)
    else:
        noise_ratio_pct = 0.0

    layers_touched = sorted({f["layer"] for f in effective_list})
    code_layers = [lyr for lyr in layers_touched if lyr not in ("tests", "docs")]

    special_case: Optional[str] = None
    if total_files == 0:
        special_case = "empty_diff"
    elif effective_files == 0:
        special_case = "skip_only"
    elif must_read_files == 0:
        special_case = "docs_or_config_only"
    elif effective_lines > 0 and (effective_deleted / effective_lines) >= 0.8 and effective_added <= 30:
        special_case = "deletion_heavy"

    has_dep_changes = any(d["added"] or d["updated"] or d["removed"] for d in dependencies)
    if total_files == 0:
        est_minutes = {"min": 0, "max": 0}
    else:
        must_weighted = sum((f["added"] + f["deleted"]) * (1.3 if f["is_risk_path"] else 1.0) for f in must_read)
        raw_min = (
            must_weighted / 18.0
            + 1.5 * must_read_files
            + skim_lines / 45.0
            + 0.5 * skim_files
            + (1.0 if has_dep_changes else 0.0)
        )
        est_minutes = {
            "min": max(1, math.floor(raw_min * 0.85)),
            "max": max(2, math.ceil(raw_min * 1.2)),
        }

    has_manual_gen_edit = any(w["code"] == "SUSPECTED_MANUAL_GEN_EDIT" for w in warnings)
    has_risk_path = any(f["is_risk_path"] for f in effective_list)

    provisional_size, size_reasons = _determine_provisional_size(
        effective_files=effective_files,
        effective_lines=effective_lines,
        code_layers=code_layers,
        special_case=special_case,
        has_manual_gen_edit=has_manual_gen_edit,
        has_risk_path=has_risk_path,
        est_max_minutes=est_minutes["max"],
    )

    must_verify: List[str] = []
    if provisional_size == "S":
        must_verify.append("size_s_single_layer_check")
    if any(d["added"] or d["updated"] for d in dependencies):
        must_verify.append("dependency_rationale_needed")
    if has_manual_gen_edit:
        must_verify.append("suspected_manual_gen_edit_review")
    if any(w["code"] == "TEST_SKIP_OR_ASSERTION_REMOVAL" for w in warnings):
        must_verify.append("test_skip_or_assertion_removal_review")
    if provisional_size == "XL":
        must_verify.append("xl_split_proposal_check")
    if any(".github/workflows/" in f["path"] for f in effective_list) and effective_files <= 2 and effective_lines < 30:
        must_verify.append("minor_ci_override_to_size_s_if_non_risk")

    return {
        "schema_version": SCHEMA_VERSION,
        "meta": {
            "repo_root": repo_root,
            "base_ref": base_ref,
            "merge_base_sha": merge_base_sha,
            "head_ref": head,
            "head_sha": head_sha,
            "mode": mode,
        },
        "summary": {
            "total_files": total_files,
            "total_added": total_added,
            "total_deleted": total_deleted,
            "total_lines": total_lines,
            "effective_files": effective_files,
            "effective_lines": effective_lines,
            "must_read_files": must_read_files,
            "must_read_lines": must_read_lines,
            "skim_files": skim_files,
            "skim_lines": skim_lines,
            "safe_to_skip_files": safe_to_skip_files,
            "safe_to_skip_lines": safe_to_skip_lines,
            "noise_ratio_pct": noise_ratio_pct,
            "provisional_size": provisional_size,
            "size_reasons": size_reasons,
            "special_case": special_case,
            "layers_touched": layers_touched,
            "estimated_review_minutes": est_minutes,
        },
        "warnings": warnings,
        "dependencies": dependencies,
        "files": {
            "must_read": must_read,
            "skim": skim,
            "safe_to_skip": safe_to_skip,
        },
        "ai_override_guidance": {
            "must_verify": must_verify,
        },
    }


def render_text_report(result: Dict[str, Any]) -> str:
    meta = result["meta"]
    s = result["summary"]
    lines = [
        f"Base: {meta['base_ref']} ({meta['merge_base_sha'][:8]}) -> Head: {meta['head_ref']} [{meta['mode']}]",
        f"Provisional Size: {s['provisional_size']} (special_case={s['special_case']})",
        (
            f"Scope: total {s['total_files']} files (+{s['total_added']}/-{s['total_deleted']} = {s['total_lines']} lines) "
            f"-> effective {s['effective_files']} files ({s['effective_lines']} lines), "
            f"noise {s['noise_ratio_pct']}%, est {s['estimated_review_minutes']['min']}-{s['estimated_review_minutes']['max']} min"
        ),
        f"Layers: {', '.join(s['layers_touched']) or '(none)'}",
        f"Reasons: {'; '.join(s['size_reasons'])}",
    ]
    if result["warnings"]:
        lines.append("Warnings:")
        for w in result["warnings"]:
            lines.append(f"  - [{w['severity'].upper()}] {w['code']} {w['path']}: {w['message']}")
    if result["dependencies"]:
        lines.append("Dependencies:")
        for d in result["dependencies"]:
            added_names = [f"{a['name']}({a['version']})" for a in d["added"]]
            upd_names = [f"{u['name']}({u['from_version']}->{u['to_version']})" for u in d["updated"]]
            lines.append(f"  - {d['manifest']}: added={added_names}, updated={upd_names}, non_dep={d['non_dependency_changes']}")
    for bucket in ("must_read", "skim", "safe_to_skip"):
        items = result["files"][bucket]
        lines.append(f"{bucket} ({len(items)}):")
        for f in items:
            lines.append(f"  - {f['status']} {f['path']} (+{f['added']}/-{f['deleted']}) [{f['reason']}]")
    return "\n".join(lines)


def _run(argv: Optional[List[str]]) -> int:
    parser = _build_parser()
    args = parser.parse_args(argv)
    if args.version:
        print(f"pr_diff_triage.py {__version__} (schema {SCHEMA_VERSION})")
        return 0
    if args.max_patch_bytes <= 0:
        _error("--max-patch-bytes は正の整数を指定してください。")
        return 2
    try:
        result = analyze_repo(
            repo_path=args.repo,
            base=args.base,
            head=args.head,
            mode=args.mode,
            max_patch_bytes=args.max_patch_bytes,
        )
    except GitError as exc:
        _error(f"pr_diff_triage.py: {exc}")
        return 2

    if args.format == "json":
        if args.pretty:
            print(json.dumps(result, ensure_ascii=False, indent=2))
        else:
            print(json.dumps(result, ensure_ascii=False))
    else:
        print(render_text_report(result))

    if sys.stdout is not None:
        sys.stdout.flush()
    return 0


def main(argv: Optional[List[str]] = None) -> int:
    try:
        _use_utf8(sys.stdout)
        return _run(argv)
    except BrokenPipeError:
        _silence_stdout()
        _error("pr_diff_triage.py: 出力先が閉じられたため、結果を最後まで書けませんでした。")
        return 3
    except Exception as error:
        if _closed_output_on_windows(error):
            _silence_stdout()
            _error("pr_diff_triage.py: 出力先が閉じられたため、結果を最後まで書けませんでした。")
            return 3
        _error(f"pr_diff_triage.py: 内部エラー: {type(error).__name__}: {error}")
        _error(traceback.format_exc().rstrip("\n"))
        return 3


if __name__ == "__main__":
    sys.exit(main())
